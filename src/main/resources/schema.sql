create table course
(
    id         bigint generated by default as identity,
    title      varchar(255) not null,
    creator_id bigint       not null,
    created_at timestamp    not null,
    updated_at timestamp,
    primary key (id)
);

create table ns_user
(
    id         bigint generated by default as identity,
    user_id    varchar(20) not null,
    password   varchar(20) not null,
    name       varchar(20) not null,
    email      varchar(50),
    created_at timestamp   not null,
    updated_at timestamp,
    primary key (id)
);

create table question
(
    id         bigint generated by default as identity,
    created_at timestamp    not null,
    updated_at timestamp,
    contents   clob,
    deleted    boolean      not null,
    title      varchar(100) not null,
    writer_id  bigint,
    primary key (id)
);

create table answer
(
    id          bigint generated by default as identity,
    created_at  timestamp not null,
    updated_at  timestamp,
    contents    clob,
    deleted     boolean   not null,
    question_id bigint,
    writer_id   bigint,
    primary key (id)
);

create table delete_history
(
    id            bigint not null,
    content_id    bigint,
    content_type  varchar(255),
    created_date  timestamp,
    deleted_by_id bigint,
    primary key (id)
);

create table cover_image
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    url        VARCHAR(1024) NOT NULL,
    size_bytes BIGINT        NOT NULL,
    width      INT           NOT NULL,
    height     INT           NOT NULL,
    type       VARCHAR(10)   NOT NULL,
    CONSTRAINT pk_cover_image PRIMARY KEY (id),
);

CREATE TABLE session
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    course_id      BIGINT           NOT NULL,
    cover_image_id BIGINT,
    start_date     DATE             NOT NULL,
    end_date       DATE             NOT NULL,
    status         VARCHAR(10)      NOT NULL,
    price          DECIMAL(12, 2)   NOT NULL,
    max_capacity   BIGINT           NOT NULL,
    enrolled_count BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT pk_session PRIMARY KEY (id),
    CONSTRAINT fk_session_course FOREIGN KEY (course_id) REFERENCES course (id),
    CONSTRAINT fk_session_cover FOREIGN KEY (cover_image_id) REFERENCES cover_image (id),
);
